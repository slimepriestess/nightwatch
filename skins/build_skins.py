#!/usr/bin/env python3
"""Build themed skins from minimal's layout.

A theme (glass/, amber/, ...) keeps only what makes it itself: tokens before
the @@BASE@@ marker, overrides after it. This script splices minimal's layout
(everything from `* { box-sizing` on) into the marker and writes skin.css, so
a layout fix lands in every themed skin at once. Moonlamp (wacky/) is
hand-built and not themed from minimal.

The persona card's usage meter wears its skin's lane-meter look (Ra, 11/19:
the usage bars looked "flatter" than the lane bars). Each theme rule that
styles a lane's context meter (`.nw-lane … [data-part="context"] …`) is
emitted a second time for `[data-part="persona-card"] … [data-part=
"usage-window"] …`, after the theme's own rules, so a theme author styles one
meter and both follow. Rules about the fold target (`--target`) are left out:
usage has no target.

Written by: claude-opus-5-5, 2026-10-05; the usage meter, 2026-11-19
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "/* @@BASE@@ (build_skins.py inserts minimal's layout here) */"
LANE, CONTEXT = '.nw-lane', '[data-part="context"]'
CARD, USAGE = '[data-part="persona-card"]', '[data-part="usage-window"]'


def blocks(css):
    """Split CSS into (prelude, body) pairs at the top level, comments dropped.
    An at-rule's body is returned whole, to be split again by its caller."""
    out, i, n = [], 0, len(css)
    while i < n:
        if css.startswith("/*", i):
            i = css.index("*/", i) + 2
            continue
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j]
        while "/*" in prelude:  # a comment between the last rule and this one
            a = prelude.index("/*")
            prelude = prelude[:a] + prelude[prelude.index("*/", a) + 2:]
        depth, k = 1, j + 1
        while depth:
            if css.startswith("/*", k):
                k = css.index("*/", k) + 2
                continue
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        out.append((prelude.strip(), css[j + 1:k - 1]))
        i = k
    return out


def usage_rules(css):
    """The theme's lane-meter rules, re-aimed at the persona card's usage meter."""
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            inner = usage_rules(body)
            if inner:
                out.append(f"{prelude} {{\n" + "\n".join("  " + r for r in inner) + "\n}")
        elif not prelude.startswith("@") and LANE in prelude and CONTEXT in prelude and "--target" not in body:
            out.append(f"{prelude.replace(LANE, CARD).replace(CONTEXT, USAGE)} {{{body}}}")
    return out


base = open(os.path.join(HERE, "minimal", "skin.css")).read()
base = base[base.index("* { box-sizing"):]
for d in sorted(os.listdir(HERE)):
    theme = os.path.join(HERE, d, "theme.css")
    if not os.path.isfile(theme):
        continue
    t = open(theme).read()
    assert MARK in t, f"{d}/theme.css has no base marker"
    out = t.replace(MARK, f"/* ---- minimal's layout (generated: edit minimal/skin.css, then run build_skins.py) ---- */\n{base}\n/* ---- {d} ---- */")
    derived = usage_rules(t[t.index(MARK) + len(MARK):])
    if derived:
        out += f"\n/* ---- {d}'s lane-meter look on the persona card's usage meter (generated by build_skins.py) ---- */\n" + "\n".join(derived) + "\n"
    open(os.path.join(HERE, d, "skin.css"), "w").write(out)
    print("built", d, f"({len(derived)} usage rules derived)")
